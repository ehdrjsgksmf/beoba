/// 조문을 가리키는 문자열의 꼴. **데이터 규약이라 여기 산다.**
///
/// 매니페스트 생성기와 검증기가 같은 규칙으로 읽어야 한다. 두 도구에 같은
/// 정규식을 따로 두고 있었고, 한쪽만 고치면 조용히 어긋난다 — 실제로 문서
/// 스캔 쪽만 띄어쓰기 정규화가 빠져 있었다.
library;

/// 「제12조」 · 「제56조의2」 · 「제64조의 5」 · 「부칙(제36056호) 제2조」.
///
/// ## 부칙 갈래가 **앞**이다
///
/// 뒤에 두면 「부칙(제36056호) 제2조」 안의 「제2조」가 짧은 갈래에 먼저
/// 걸려서, 부칙 인용이 통째로 본문 인용으로 읽힌다.
///
/// **부칙은 개정되지 않는다.** 법이 고쳐지면 새 부칙이 하나 더 붙고 옛 부칙은
/// 그대로 남는다. 그래서 부칙 번호까지 적으면 그 인용은 영원히 유일하고,
/// 본문 제2조와 문자열이 겹치지 않는다(DECISIONS 126번).
final RegExp articleRefPattern = RegExp(
  r'부칙\s?\(\s?제[\d\-]+호\s?\)\s?제\s?\d+조(?:의\s?\d+)?'
  r'|제\s?\d+조(?:의\s?\d+)?',
);

/// 매니페스트에 적히는 꼴. **띄어쓰기를 지운다.**
///
/// 「제64조의 5」와 「제64조의5」가 다른 조문이 되면, 원문을 갖고 있는데도
/// 못 가진 것으로 세어진다.
String normalizeArticleRef(String ref) => ref.replaceAll(' ', '');

/// 문자열에 든 조문 참조 전부. 이미 정규화돼 있다.
Set<String> articleRefsIn(String text) => articleRefPattern
    .allMatches(text)
    .map((match) => normalizeArticleRef(match.group(0)!))
    .toSet();
